"""V6 STEP 2 — timing truth. Snaps sentence boundaries to waveform silence,
writes src/videos/video-6-use-state/timing.ts + scripts/v6/timing.json."""
import json, os, subprocess, wave

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
V6 = os.path.join(BASE, "scripts", "v6")
OUT_DIR = os.path.join(BASE, "src", "videos", "video-6-use-state")
SR = 48000
FPS = 30

import numpy as np

FF = os.path.join(BASE, "node_modules", "@remotion", "compositor-win32-x64-msvc", "ffmpeg.exe")

subprocess.run([FF, "-hide_banner", "-loglevel", "error", "-y",
                "-i", os.path.join(V6, "narration_raw.mp3"),
                "-ac", "1", "-ar", str(SR), os.path.join(V6, "narration.wav")], check=True)

wf = wave.open(os.path.join(V6, "narration.wav"), "rb")
a = np.frombuffer(wf.readframes(wf.getnframes()), dtype=np.int16).astype(np.float32) / 32768.0
wf.close()
dur = len(a) / SR
rms_all = np.sqrt(np.mean(a ** 2))
peak_all = np.max(np.abs(a))
print(f"audio {dur:.2f}s rms {rms_all:.4f} peak {peak_all:.3f}")

HOP = int(0.02 * SR)
n = len(a) // HOP
env = np.sqrt(np.mean(a[: n * HOP].reshape(n, HOP) ** 2, axis=1) + 1e-12)

def snap(t, win=0.35):
    i = int(t / 0.02)
    lo, hi = max(0, i - int(win / 0.02)), min(n, i + int(win / 0.02))
    seg = env[lo:hi]
    return (lo + int(np.argmin(seg))) * 0.02

ev = json.load(open(os.path.join(V6, "events.json")))
out = []
for s in ev["sentences"]:
    ss = snap(max(0.0, s["start"]))
    ee = snap(min(dur - 0.05, s["end"]))
    if ee <= ss:
        ee = ss + 0.1
    out.append({"text": s["text"], "s": round(ss, 3), "e": round(ee, 3)})

for i in range(1, len(out)):
    if out[i]["s"] < out[i - 1]["s"]:
        out[i]["s"] = out[i - 1]["s"]
    if out[i]["e"] < out[i]["s"]:
        out[i]["e"] = out[i]["s"] + 0.05

total = round((out[-1]["e"] + 1.0) * FPS)

lines = [
    "/* GENERATED by scripts/measure_v6.py — do not edit by hand.",
    " * Sentence windows snapped to waveform silence midpoints.",
    " * Regenerate:  python scripts/tts_v6.py && python scripts/measure_v6.py",
    " */",
    "",
    f"export const FPS = {FPS};",
    "",
    f"export const ADURATION = {total};",
    "",
    "export type Sent = { text: string; s: number; e: number };",
    "",
    "export const SENT: Sent[] = [",
]
for o in out:
    t = o["text"].replace("\\", "\\\\").replace('"', '\\"')
    lines.append(f'    {{ text: "{t}", s: {round(o["s"] * FPS)}, e: {round(o["e"] * FPS)} }},')
lines.append("];")

os.makedirs(OUT_DIR, exist_ok=True)
open(os.path.join(OUT_DIR, "timing.ts"), "w", encoding="utf-8", newline="\n").write("\n".join(lines))
json.dump(out, open(os.path.join(V6, "timing.json"), "w"), indent=1)

print(f"{len(out)} sentences; ADURATION={total} frames ({total / FPS:.2f}s)")
for i, o in enumerate(out):
    print(f'{i:2d} {o["s"]:7.2f} {o["e"]:7.2f}  {o["text"][:58]}')
